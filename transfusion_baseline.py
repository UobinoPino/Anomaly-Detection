"""TransFusion-style anomaly detection baseline (per-class trainer + inferer).

A faithful re-implementation of the core ideas of TransFusion (Fucka et al.,
ECCV 2024 — github.com/MaticFuc/ECCV_TransFusion) adapted to match the I/O
contract of the v6 stacker. Outputs:

  - submission.csv             (q8rle-encoded test predictions)
  - local_predictions.npz      (val predictions + GT masks, for stacking)
  - run_log.txt                (training + inference log)

Key ideas (paraphrased from the paper):
  1. Synthetic anomalies are generated by alpha-blending textures from
     OTHER classes into normal images (no DTD dependency).
  2. A "transparency-based" forward process: at timestep t ∈ [0, T], the
     anomalous region is t/T transparent, so x_t = (1 - α(t)·M)·x_0 + α(t)·M·A.
  3. A U-Net with sinusoidal-time conditioning predicts BOTH (a) the anomaly
     mask at the current transparency level, and (b) the reconstructed normal.
  4. At inference, we run the network at a small set of timesteps and average
     the predicted masks. This is the multi-step inference TransFusion uses,
     simplified to a fixed schedule for predictable cost on a 4090.

Memory budget: ~12 GB VRAM at input 384, batch 8, ~30M params.
Per-class training time on a 4090: ~3 hours for 50k iters.

This script is designed to be a *drop-in* sibling of patchcore_baseline_v2.py
and fastflow_baseline.py. After it runs, splice_for_stacker.py merges its
class_03/class_07 predictions into a base method to produce a 16th stacker
column that doesn't break alignment.
"""
